package operators;

public class RelationalOperator {
	
	public static void main(String[] args) {
		//RELATIONAL OPERTOR!!! PRIMITIVE DATA TYPE and NUMBERS
		// > , < , >= , <= , == , !=
		int number1 = 5;
		int number2 = 10;
		
		System.out.println(number1 >  number2);
		System.out.println(number1 <  number2);
		System.out.println(number1 >=  number2);
		System.out.println(number1 <=  number2);
		System.out.println(number1 ==  number2);
		System.out.println(number1 !=  number2);
	}

}
